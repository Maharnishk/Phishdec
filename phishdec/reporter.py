"""Reporting: JSON, CSV, self-contained HTML."""
from __future__ import annotations

import csv
import html
import json
import os
from datetime import datetime, timezone


def _stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")


def save_json(results: list[dict], path: str) -> str:
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"generated_at": _stamp(), "count": len(results),
                   "results": results}, f, indent=2, default=str)
    return path


def save_csv(results: list[dict], path: str) -> str:
    fields = ["domain", "technique", "registered", "score", "verdict",
              "distance", "entropy", "risk_reasons", "registered_reasons"]
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in results:
            w.writerow({k: ("; ".join(map(str, r.get(k, [])))
                            if isinstance(r.get(k), list) else r.get(k, ""))
                        for k in fields})
    return path


