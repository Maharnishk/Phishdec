def save_html(results: list[dict], path: str, legit: str = "") -> str:
    from collections import Counter
    counts = Counter(r.get("verdict", "?") for r in results)
    badges = "".join(f'<span class="{html.escape(k)}">{html.escape(k)}: {v}</span>'
                     for k, v in counts.most_common())
    rows = []
    for r in results:
        why = "; ".join(r.get("risk_reasons", []) + r.get("reasons_reg", []))
        rows.append(
            f'<tr class="{"reg" if r.get("registered") else ""}">'
            f'<td><b>{html.escape(r.get("domain", ""))}</b></td>'
            f'<td>{html.escape(r.get("technique", ""))}</td>'
            f'<td>{"YES" if r.get("registered") else "no"}</td>'
            f'<td>{r.get("score", 0)}</td>'
            f'<td><span class="{html.escape(r.get("verdict", ""))} badges">'
            f'<span class="{html.escape(r.get("verdict", ""))}">{html.escape(r.get("verdict", ""))}</span></span></td>'
            f'<td class="small">{html.escape(why[:400])}</td></tr>')
    with open(path, "w", encoding="utf-8") as f:
        f.write(HTML_TMPL.format(legit=html.escape(legit), count=len(results),
                                 nreg=sum(1 for r in results if r.get("registered")),
                                 ts=html.escape(_stamp()), badges=badges,
                                 rows="\n".join(rows)))
    return path


def save_report(results: list[dict], basename: str = "phishdec_report",
                formats: tuple = ("json", "html", "csv"),
                legit: str = "") -> list[str]:
    out = []
    base, _ = os.path.splitext(basename)
    if "json" in formats:
        out.append(save_json(results, base + ".json"))
    if "csv" in formats:
        out.append(save_csv(results, base + ".csv"))
    if "html" in formats:
        out.append(save_html(results, base + ".html", legit=legit))
    return out
